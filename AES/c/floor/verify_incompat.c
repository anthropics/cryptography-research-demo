    printf("  (a,a,0,..)∈LS ⟹ G_a⊆LS [A3, S_255-closure]\n");
    printf("  G_a⊆LS + Borel-inv ⟹ ⟨G_a,scale⟩-inv [I1] ⟹ all-G_b-inv [I2]\n");
    printf("  all-G_b-inv + scale-inv ⟹ ≤1 bit [I6]  ⟹⟸ ≥88b: CONTRADICTION\n");
