    printf("  E-trans-inv + Borel-inv ⟹ PGL-inv [I4]\n");
    printf("  ∴ dim(LS(fp)) ∈ {0, 8}\n");
    printf("\n  ⟹ ℓ ≥ 255 - 8/8 = 254  (LINEAR-STRUCTURE, floor-81.1 §3)\n");
    printf("  ⟹ T ≥ 2^{88} × 254/160 = 2^{88.667}  [PROVEN A1-FLOOR]\n");
